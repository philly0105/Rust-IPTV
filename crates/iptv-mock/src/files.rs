//! Download test files: `/files/video.bin`, `/files/flaky.bin`,
//! `/files/nolen.bin`.
//!
//! Content is deterministic: byte `i` of every file is [`video_byte`]`(i)`,
//! so a test can verify a resumed download byte for byte with
//! [`video_bytes`] instead of keeping a copy.
//!
//! Query options (all optional, all routes):
//! - `size=<bytes>`: override the length (default 20 MiB; nolen 3 MiB).
//! - `kbps=<KiB/s>`: throttle, so a test can pause mid-transfer.
//! - `key=<name>` (flaky only): each distinct key fails once.

use std::sync::Arc;

use axum::extract::{Query, State};
use axum::http::HeaderMap;
use axum::response::Response;
use bytes::Bytes;
use serde::Deserialize;

use crate::catalog::mix;
use crate::media::{serve_bytes, Producer, ServeOpts};
use crate::MockState;

/// Default length of `video.bin` and `flaky.bin` (20 MiB).
pub const VIDEO_BIN_LEN: u64 = 20 * 1024 * 1024;
/// `flaky.bin` drops the connection after this many body bytes, once.
pub const FLAKY_DROP_AFTER: u64 = 5 * 1024 * 1024;
/// Default length of `nolen.bin` (3 MiB).
pub const NOLEN_LEN: u64 = 3 * 1024 * 1024;
/// Upper bound for `?size=` (1 GiB), so a typo cannot stream forever.
pub const MAX_SIZE: u64 = 1024 * 1024 * 1024;

/// Byte `i` of every generated file.
pub fn video_byte(i: u64) -> u8 {
    (mix(i / 8) >> ((i % 8) * 8)) as u8
}

/// `len` generated bytes starting at `offset`.
pub fn video_bytes(offset: u64, len: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(len);
    let mut i = offset;
    let end = offset + len as u64;
    // Head until 8-aligned.
    while i < end && i % 8 != 0 {
        out.push(video_byte(i));
        i += 1;
    }
    while i + 8 <= end {
        out.extend_from_slice(&mix(i / 8).to_le_bytes());
        i += 8;
    }
    while i < end {
        out.push(video_byte(i));
        i += 1;
    }
    out
}

/// Strong ETag for a generated file of `len` bytes.
pub fn etag_for(len: u64) -> String {
    format!("\"iptv-mock-video-{len:x}\"")
}

#[derive(Debug, Default, Deserialize)]
pub struct FileOpts {
    pub size: Option<u64>,
    pub kbps: Option<u64>,
    pub key: Option<String>,
}

fn producer() -> Producer {
    Box::new(|o, n| Bytes::from(video_bytes(o, n)))
}

fn opts(len: u64, kbps: u64, filename: &str) -> ServeOpts {
    let mut o = ServeOpts::new("application/octet-stream").etag(etag_for(len));
    o.kbps = kbps;
    o.filename = Some(filename.to_string());
    o
}

pub(crate) async fn video(headers: HeaderMap, Query(q): Query<FileOpts>) -> Response {
    let len = q.size.unwrap_or(VIDEO_BIN_LEN).min(MAX_SIZE);
    serve_bytes(
        &headers,
        len,
        producer(),
        opts(len, q.kbps.unwrap_or(0), "video.bin"),
    )
}

pub(crate) async fn flaky(
    State(state): State<Arc<MockState>>,
    headers: HeaderMap,
    Query(q): Query<FileOpts>,
) -> Response {
    let len = q.size.unwrap_or(VIDEO_BIN_LEN).min(MAX_SIZE);
    let key = q.key.clone().unwrap_or_default();
    let first = state.flaky_seen.lock().insert(key.clone());
    let mut o = opts(len, q.kbps.unwrap_or(0), "flaky.bin");
    if first {
        tracing::info!(
            key,
            "flaky.bin: dropping this response after {FLAKY_DROP_AFTER} bytes"
        );
        o.fail_after = Some(FLAKY_DROP_AFTER);
    }
    serve_bytes(&headers, len, producer(), o)
}

pub(crate) async fn nolen(headers: HeaderMap, Query(q): Query<FileOpts>) -> Response {
    let len = q.size.unwrap_or(NOLEN_LEN).min(MAX_SIZE);
    let mut o = ServeOpts::new("application/octet-stream");
    o.ranges = false;
    o.content_length = false;
    o.kbps = q.kbps.unwrap_or(0);
    o.filename = Some("nolen.bin".to_string());
    // Range headers are ignored: always 200 with the whole body, chunked.
    let mut stripped = headers;
    stripped.remove(axum::http::header::RANGE);
    serve_bytes(&stripped, len, producer(), o)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn video_bytes_matches_bytewise() {
        for (off, len) in [
            (0u64, 100usize),
            (3, 29),
            (8, 8),
            (1_000_003, 77),
            (VIDEO_BIN_LEN - 5, 5),
        ] {
            let fast = video_bytes(off, len);
            let slow: Vec<u8> = (off..off + len as u64).map(video_byte).collect();
            assert_eq!(fast, slow, "offset {off}");
        }
    }
}
